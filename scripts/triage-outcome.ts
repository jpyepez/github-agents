/// <reference types="bun" />
// The triage outcome check, run by `apply` before it writes anything. The triage agent
// holds no write token: it leaves three files in its output folder, and this checks them.
//
//   decision.json  {"category": "<category label>", "outcome": "<outcome role>", "retitle": "<new title>"}
//                  `outcome` is a role: ready, needs-info, ready-for-human or wontfix. agents.yml
//                  maps each role to the repo's label. `retitle` is optional.
//   comment.md     the reasons, point by point. `apply` adds the AI disclaimer on top.
//   spec.md        for `ready` only: the spec that becomes the issue body.
//
//   bun scripts/triage-outcome.ts <out-dir> <settings.json> <check.json> <issue-number> <plan.json>
//
// On a pass it writes plan.json, with the labels to add and remove and the board column;
// on a fail it prints a ::error:: line, exits 1 and `apply` writes nothing.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { CheckResult } from "./check";
import type { ColumnRole, LabelRole, Settings } from "./settings";
import { Tracker } from "./tracker";

export const OUTCOMES = ["ready", "needs-info", "ready-for-human", "wontfix"] as const;
export type Outcome = (typeof OUTCOMES)[number];

export const DISCLAIMER = "> *This was generated by AI during triage.*";
// GitHub's limit for an issue body or comment is 65536 characters; leave room for the disclaimer.
export const MAX_BODY = 60000;
export const MAX_TITLE = 256;

export type TriageFiles = { decision: string | null; comment: string | null; spec: string | null };
export type TriageDecision = { category: string; outcome: Outcome; retitle: string | null };
export type Validated =
  | { pass: true; decision: TriageDecision; comment: string; spec: string | null }
  | { pass: false; reason: string };

const fail = (reason: string): Validated => ({ pass: false, reason });

export function validateTriage(files: TriageFiles, settings: Settings, readyAllowed: boolean): Validated {
  if (files.decision === null) return fail("decision.json is missing");
  let raw: unknown;
  try {
    raw = JSON.parse(files.decision);
  } catch {
    return fail("decision.json isn't valid JSON");
  }
  if (typeof raw !== "object" || raw === null || Array.isArray(raw)) return fail("decision.json must be a JSON object");
  const d = raw as Record<string, unknown>;
  const unknown = Object.keys(d).filter((k) => !["category", "outcome", "retitle"].includes(k));
  if (unknown.length) return fail(`decision.json has unknown keys: ${unknown.join(", ")}`);

  if (typeof d.category !== "string" || !settings.categories.includes(d.category)) {
    return fail(`decision.json's category must be one of ${settings.categories.join(", ")}, got ${JSON.stringify(d.category)}`);
  }
  if (typeof d.outcome !== "string" || !(OUTCOMES as readonly string[]).includes(d.outcome)) {
    return fail(`decision.json's outcome must be one of ${OUTCOMES.join(", ")}, got ${JSON.stringify(d.outcome)}`);
  }
  const outcome = d.outcome as Outcome;
  if (outcome === "ready" && !readyAllowed) {
    return fail("the outcome is ready, but this repo has no ready bar or hand-back list, so triage may not apply it");
  }

  let retitle: string | null = null;
  if (d.retitle !== undefined && d.retitle !== null) {
    if (typeof d.retitle !== "string" || d.retitle.trim() === "" || d.retitle.includes("\n") || d.retitle.length > MAX_TITLE) {
      return fail(`decision.json's retitle must be one line of 1 to ${MAX_TITLE} characters`);
    }
    retitle = d.retitle.trim();
  }

  const comment = files.comment?.trim() ?? "";
  if (comment === "") return fail("comment.md is missing or empty");
  if (comment.length > MAX_BODY) return fail(`comment.md is longer than ${MAX_BODY} characters`);

  const spec = files.spec?.trim() ?? "";
  if (outcome === "ready") {
    if (spec === "") return fail("the outcome is ready, but spec.md is missing or empty");
    if (spec.length > MAX_BODY) return fail(`spec.md is longer than ${MAX_BODY} characters`);
    if (!/^\s*- \[ \] \S/m.test(spec)) return fail("spec.md has no acceptance criteria as a `- [ ]` checklist");
  } else if (spec !== "") {
    return fail(`spec.md is only for ready, but the outcome is ${outcome}`);
  }

  return { pass: true, decision: { category: d.category, outcome, retitle }, comment, spec: outcome === "ready" ? spec : null };
}

export type LabelPlan = { add: string[]; remove: string[] };

// Adds the category and the outcome; removes needs-triage and every other category and
// outcome already on the issue. One edit, applied last by `apply`.
export function labelPlan(decision: TriageDecision, current: string[], settings: Settings): LabelPlan {
  const outcomeLabel = settings.labels[decision.outcome as LabelRole];
  const managed = new Set([...settings.categories, ...OUTCOMES.map((o) => settings.labels[o]), settings.labels["needs-triage"]]);
  const add = [decision.category, outcomeLabel].filter((l) => !current.includes(l));
  const remove = current.filter((l) => managed.has(l) && l !== decision.category && l !== outcomeLabel);
  return { add, remove };
}

// The board column a passing triage moves the issue to, or null to leave it alone.
export function statusFor(outcome: Outcome, assigned: boolean): ColumnRole | null {
  // HITL is everything waiting on the owner.
  if (outcome !== "ready") return "hitl";
  // Someone may already have claimed it and moved it to In progress.
  return assigned ? null : "ready";
}

export function withDisclaimer(text: string): string {
  return `${DISCLAIMER}\n\n${text.trim()}\n`;
}

function readOrNull(path: string): string | null {
  return existsSync(path) ? readFileSync(path, "utf8") : null;
}

if (import.meta.main) {
  const [outDir = "", settingsPath = "", checkPath = "", issueArg = "", planPath = "plan.json"] = process.argv.slice(2);
  try {
    if (!outDir || !settingsPath || !checkPath || !/^[1-9]\d*$/.test(issueArg)) {
      throw new Error("Usage: bun scripts/triage-outcome.ts <out-dir> <settings.json> <check.json> <issue-number> <plan.json>");
    }
    const settings = JSON.parse(readFileSync(settingsPath, "utf8")) as Settings;
    const check = JSON.parse(readFileSync(checkPath, "utf8")) as CheckResult;
    const files = {
      decision: readOrNull(join(outDir, "decision.json")),
      comment: readOrNull(join(outDir, "comment.md")),
      spec: readOrNull(join(outDir, "spec.md")),
    };
    const result = validateTriage(files, settings, check.readyAllowed);
    if (!result.pass) {
      console.log(`::error::#${issueArg} failed the triage outcome check: ${result.reason}. Nothing was written; re-dispatch Triage.`);
      process.exit(1);
    }
    const repo = process.env.GITHUB_REPOSITORY;
    if (!repo) throw new Error("GITHUB_REPOSITORY isn't set.");
    const issue = new Tracker(repo).issue(Number(issueArg));
    const plan = {
      ...result,
      labels: labelPlan(result.decision, issue.labels, settings),
      status: statusFor(result.decision.outcome, issue.assignees.length > 0),
    };
    writeFileSync(planPath, JSON.stringify(plan, null, 2) + "\n");
    console.log(`#${issueArg} triage outcome passed: ${result.decision.category}, ${result.decision.outcome}`);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.log(`::error::${message.split("\n")[0]}`);
    console.error(message);
    process.exit(1);
  }
}
